package com.application.sync.ui.components.button

enum class ButtonVariant {
    /*
    Represents the default button variant.
    */
    Default,

    /*
    Represents a button variant with a primary emphasis.
     */
    Secondary,

    /*
    Represents a button variant that indicates a successful action.
     */
    Success,

    /*
    Represents a button variant that indicates an error or destructive action.
     */
    Error
}
